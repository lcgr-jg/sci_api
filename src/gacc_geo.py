def coords_for_destination(name: str) -> tuple[float, float] | None:
    """Return (lat, lon) for a canonical or raw GACC partner name."""
    if not name or (isinstance(name, float) and pd.isna(name)):
        return None
    key = str(name).strip()
    if key in COUNTRY_CENTROIDS:
        return COUNTRY_CENTROIDS[key]
    # Case-insensitive fallback.
    lower_map = {k.casefold(): v for k, v in COUNTRY_CENTROIDS.items()}
    return lower_map.get(key.casefold())
